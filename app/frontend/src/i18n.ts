export type I18nKey = keyof typeof zh;

export function translate(language: ShellLanguage, key: I18nKey, vars?: Vars): string {
  const table = language === 'en' ? en : zh;
  let s: string = table[key] ?? zh[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

export function useI18n() {
  const language = useUiStore((s) => s.language);
  const t = useCallback((key: I18nKey, vars?: Vars) => translate(language, key, vars), [language]);
  return { language, t };
}

export function getUSMarketStatus(language: ShellLanguage) {
  const formatter = new Intl.DateTimeFormat('en-US', {
    timeZone: 'America/New_York',
    hour12: false,
    year: 'numeric',
    month: 'numeric',
    day: 'numeric',
    hour: 'numeric',
    minute: 'numeric',
    weekday: 'short',
  });
  const closed = { text: translate(language, 'marketClosed'), color: 'bg-faint' };
  try {
    const parts = formatter.formatToParts(new Date());
    const dict: Record<string, string> = {};
    parts.forEach((p) => {
      dict[p.type] = p.value;
    });
    const weekday = dict.weekday;
    const hour = parseInt(dict.hour, 10);
    const minute = parseInt(dict.minute, 10);
    if (weekday === 'Sat' || weekday === 'Sun') {
      return { text: translate(language, 'marketWeekend'), color: 'bg-faint' };
    }
    const timeInMinutes = hour * 60 + minute;
    const openTime = 9 * 60 + 30;
    const closeTime = 16 * 60;
    if (timeInMinutes >= openTime && timeInMinutes < closeTime) {
      return { text: translate(language, 'marketOpen'), color: 'bg-up' };
    }
    if (timeInMinutes >= 4 * 60 && timeInMinutes < openTime) {
      return { text: translate(language, 'marketPremarket'), color: 'bg-accent' };
    }
    if (timeInMinutes >= closeTime && timeInMinutes < 20 * 60) {
      return { text: translate(language, 'marketPostmarket'), color: 'bg-accent' };
    }
    return closed;
  } catch {
    return closed;
  }
}
